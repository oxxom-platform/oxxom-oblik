"""Build the public JS dictionary from the same catalog used by Django."""
import json
import re
from collections import Counter
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = json.loads((root / 'backend/core/locale/ui.json').read_text(encoding='utf-8'))
for source, values in rows.items():
    if not isinstance(source, str) or len(values) != 3 or not all(isinstance(v, str) and v for v in values):
        raise ValueError(f'Incomplete translation: {source}')
    placeholders = Counter(re.findall(r'\{\d+\}', source))
    if any(Counter(re.findall(r'\{\d+\}', value)) != placeholders for value in values):
        raise ValueError(f'Translation placeholders differ: {source}')
(root / 'backend/core/static/core/ui/translations.js').write_text(
    '/* Generated by scripts/build-ui-locales.py. UI copy only. */\nwindow.OxxomTranslations=' +
    json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
